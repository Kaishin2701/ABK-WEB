const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'modules/watermark.js'), 'utf8');
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const code = source.slice(source.indexOf('function drawTextBoxes('), source.indexOf('function processImage('));
const context = vm.createContext({ textEnabled: { checked: false } });
vm.runInContext(code, context);
const labels = [];
const ctx = { save(){}, restore(){}, scale(){}, measureText(s){ return { width: s.length * 18 }; }, beginPath(){}, moveTo(){}, arcTo(){}, closePath(){}, fill(){}, stroke(){}, fillText(s){ labels.push(s); } };
const text = { title: 'Chelsea Home', type: 'Kids Kit', mode: 'player', playerText: 'PALMER 10' };
context.drawTextBoxes(ctx, 1000, 1000, text);
assert.deepEqual(labels, []);
context.textEnabled.checked = true;
context.drawTextBoxes(ctx, 1000, 1000, { ...text, title: '' });
assert.deepEqual(labels, []);
context.drawTextBoxes(ctx, 1000, 1000, text);
assert.deepEqual(labels, ['Chelsea Home', 'Kids Kit', 'PALMER 10']);
context.textEnabled.checked = false;
context.drawTextBoxes(ctx, 1000, 1000, text);
assert.equal(labels.length, 3);
context.textEnabled.checked = true;
context.drawTextBoxes(ctx, 600, 800, { ...text, mode: 'optional' });
assert.equal(labels.at(-1), 'Optional Personalisation');
assert.match(html, /id="wm-text-enabled" type="checkbox"/);
assert.match(source, /itemDraft\.text = \{ title: textTitle\.value/);
assert.match(source, /itemSettings\.set\(editingFile, \{ \.\.\.itemDraft \}\)/);
const geometryCode = source.slice(source.indexOf('function imageLayerRect('), source.indexOf('function processImage('));
vm.runInContext(geometryCode, context);
const rect = (w, h, transform) => JSON.parse(JSON.stringify(context.imageLayerRect(w, h, transform)));
assert.deepEqual(rect(1000, 800), { x: 0, y: 0, width: 1000, height: 800 });
assert.deepEqual(rect(1000, 800, { zoom: 0.5, x: 0.1, y: -0.1 }), { x: 350, y: 120, width: 500, height: 400 });
assert.deepEqual(rect(500, 400, { zoom: 0.5, x: 0.1, y: -0.1 }), { x: 175, y: 60, width: 250, height: 200 });
assert.equal(rect(1000, 800, { zoom: 9 }).width, 3000);
assert.match(source, /drawImage\(img, rect\.x, rect\.y, rect\.width, rect\.height\)[\s\S]*?if\(watermark\)[\s\S]*?drawTextBoxes\(ctx, canvas\.width, canvas\.height, text\)/);
assert.match(html, /id="wm-item-reset-transform"/);
assert.match(source, /itemDraft\.transform = \{ zoom: 1, x: 0, y: 0 \}/);
console.log('Unified watermark text box tests passed.');
